PROFILE_NAMES: List[str] = list(JD_PROFILES.keys())


def get_profile(name: str) -> dict | None:
    """按名称获取岗位画像；未知名称返回 None。"""
    return JD_PROFILES.get(name)


def profile_jd_text(name: str) -> str:
    """拼接岗位画像的 JD 模板文本，供知识库一键导入。"""
    profile = JD_PROFILES.get(name)
    if not profile:
        return ""
    lines = [f"【{name} · 内置画像】", profile["jd_template"], "面试关注点："]
    lines.append("、".join(profile["focus"]))
    lines.append("核心技能要求：")
    lines.extend(f"- {skill}" for skill in profile["skills"])
    return "\n".join(lines)
